/**
 * Extract terms for indexing & matching: CJK bigrams + ASCII word tokens + numbers.
 * Deterministic; no dictionary segmentation (X3: cheap and predictable).
 */
export function extractTerms(normalized: string): string[] {
  const terms = new Set<string>();
  // ASCII words & numbers
  const asciiTokens = normalized.match(/[a-z0-9][a-z0-9_-]{0,63}/g) ?? [];
  for (const t of asciiTokens) terms.add(t);
  // CJK runs → bigrams (and single char when run length is 1)
  const cjkRuns = normalized.match(/[\u4e00-\u9fff]+/g) ?? [];
  for (const run of cjkRuns) {
    const chars = Array.from(run);
    if (chars.length === 1) {
      terms.add(chars[0]!);
    } else {
      for (let i = 0; i + 1 < chars.length; i++) {
        terms.add(chars[i]! + chars[i + 1]!);
      }
    }
  }
  return [...terms];
}

