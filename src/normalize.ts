// The pipeline
// ---------------------------------------------------------------------------

export interface Normalized {
  /** Simplified + half-width + lowercased text. */
  text: string;
  /** Terms extracted from the normalized text. */
  terms: string[];
}

export function normalize(input: string): Normalized {
  const text = toSimplified(toHalfWidth(input)).toLowerCase();
  return { text, terms: extractTerms(text) };
}

/**
 * Expand a query with seed synonym groups (X3 second level).
 * Each group is a list of interchangeable tokens; any hit expands to the whole group.
 * Returns unique tokens (original + expansions), lowercase-normalized.
 */
export function expandSynonyms(query: string, groups: string[][]): string[] {
  const base = normalize(query).terms;
  const out = new Set<string>(base);
  for (const group of groups) {
    const normGroup = group.map((g) => normalize(g).text).filter(Boolean);
    if (normGroup.some((g) => base.includes(g))) {
      for (const g of normGroup) out.add(g);
    }
  }
  return [...out];
}
